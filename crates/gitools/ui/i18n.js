/** Względem angielskiego tekstu w szablonach aplikacji. */
let lang = 'pl';

/**
 * Tłumaczy klucz; w `{placeholder}` podstawiamy wartości z `vars`.
 * Brakujący klucz pokazuje sam klucz, żeby błąd był widoczny.
 */
function t(key, vars) {
  const table = I18N[lang] || I18N.pl;
  let text = table[key] ?? I18N.pl[key] ?? key;

  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }

  return text;
}

/** Podstawia tłumaczenia we wszystkich elementach z `data-i18n`. */
function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll('[data-i18n-html]')) {
    node.innerHTML = t(node.dataset.i18nHtml);
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
  }
}